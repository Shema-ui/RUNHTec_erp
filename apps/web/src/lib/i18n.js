const DICTS = { rw: RW, fr: FR };
const KEY = 'runhtec-lang';

let current = 'en';
try { current = localStorage.getItem(KEY) || 'en'; } catch { /* private mode */ }
if (!DICTS[current] && current !== 'en') current = 'en';
const listeners = new Set();

export function setLang(code) {
  current = DICTS[code] || code === 'en' ? code : 'en';
  try { localStorage.setItem(KEY, current); } catch { /* ignore */ }
  try { document.documentElement.lang = current; } catch { /* ignore */ }
  listeners.forEach((l) => l());
}
export const getLang = () => current;

// t('Visit: {date}', { date: 'Mon 3 Nov' })
export function translate(text, vars, lang = current) {
  let out = (DICTS[lang] && DICTS[lang][text]) || text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v ?? ''));
  return out;
}

// In a component:  const { t, lang, setLang } = useLang();
export function useLang() {
  const lang = useSyncExternalStore((cb) => { listeners.add(cb); return () => listeners.delete(cb); }, () => current, () => 'en');
  return { lang, setLang, t: (text, vars) => translate(text, vars, lang) };
}

// Dates in the chosen language.
export const locale = () => (current === 'fr' ? 'fr-FR' : current === 'rw' ? 'rw-RW' : undefined);
