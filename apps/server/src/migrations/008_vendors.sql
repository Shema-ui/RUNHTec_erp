-- Suppliers (vendors) and the items + prices they give us.
CREATE TABLE IF NOT EXISTS vendors (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  contact_name VARCHAR(200) DEFAULT '',
  phone VARCHAR(60) DEFAULT '',
  email VARCHAR(200) DEFAULT '',
  address VARCHAR(500) DEFAULT '',
  supplies VARCHAR(500) DEFAULT '',
  currency VARCHAR(10) DEFAULT 'RWF',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  notes TEXT,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS vendor_items (
  id VARCHAR(20) PRIMARY KEY,
  vendor VARCHAR(20) NOT NULL,
  name VARCHAR(200) NOT NULL,
  brand VARCHAR(120) DEFAULT '',
  code VARCHAR(80) DEFAULT '',
  category VARCHAR(60) DEFAULT '',
  unit VARCHAR(30) DEFAULT 'pcs',
  price DECIMAL(14,2) NOT NULL DEFAULT 0,
  previous_price DECIMAL(14,2) DEFAULT NULL,
  price_changed_at DATETIME NULL,
  currency VARCHAR(10) DEFAULT 'RWF',
  availability VARCHAR(20) DEFAULT 'in_stock',
  lead_time VARCHAR(60) DEFAULT '',
  notes VARCHAR(1000) DEFAULT '',
  updated_by_name VARCHAR(200) DEFAULT '',
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_vitem_vendor (vendor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
