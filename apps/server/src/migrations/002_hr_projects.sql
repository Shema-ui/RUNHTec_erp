-- HR & contractors (per-project engagement model), project team
-- assignments and website job applications. Every statement is safe to
-- run on each start (IF NOT EXISTS). Extra columns on existing tables are
-- added by ensureColumn() in migrate.js.

CREATE TABLE IF NOT EXISTS contractors (
  id VARCHAR(20) PRIMARY KEY,
  code VARCHAR(20) DEFAULT '',
  full_name VARCHAR(200) NOT NULL DEFAULT '',
  email VARCHAR(190) DEFAULT '',
  phone VARCHAR(40) DEFAULT '',
  whatsapp VARCHAR(40) DEFAULT '',
  department VARCHAR(40) NOT NULL DEFAULT 'technical',
  trade VARCHAR(60) DEFAULT '',
  skills JSON DEFAULT NULL,
  experience_years INT DEFAULT 0,
  qualifications VARCHAR(1000) DEFAULT '',
  certifications VARCHAR(1000) DEFAULT '',
  country VARCHAR(80) DEFAULT 'Rwanda',
  city VARCHAR(80) DEFAULT '',
  rate_amount DECIMAL(14,2) DEFAULT 0,
  rate_unit VARCHAR(20) DEFAULT 'per_day',
  currency VARCHAR(10) DEFAULT 'RWF',
  has_tools TINYINT(1) NOT NULL DEFAULT 0,
  has_transport TINYINT(1) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'available',
  verified TINYINT(1) NOT NULL DEFAULT 0,
  rating DECIMAL(3,1) DEFAULT 0,
  cv VARCHAR(20) DEFAULT NULL,
  id_document VARCHAR(20) DEFAULT NULL,
  certificate_file VARCHAR(20) DEFAULT NULL,
  emergency_contact VARCHAR(200) DEFAULT '',
  payment_details VARCHAR(300) DEFAULT '',
  notes VARCHAR(2000) DEFAULT '',
  source VARCHAR(20) DEFAULT 'manual',
  application VARCHAR(20) DEFAULT NULL,
  user VARCHAR(20) DEFAULT NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_contractors_department (department),
  INDEX idx_contractors_status (status),
  INDEX idx_contractors_trade (trade)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS job_applications (
  id VARCHAR(20) PRIMARY KEY,
  ref VARCHAR(20) DEFAULT '',
  full_name VARCHAR(200) NOT NULL DEFAULT '',
  email VARCHAR(190) DEFAULT '',
  phone VARCHAR(40) DEFAULT '',
  whatsapp VARCHAR(40) DEFAULT '',
  country VARCHAR(80) DEFAULT '',
  city VARCHAR(80) DEFAULT '',
  department VARCHAR(40) DEFAULT 'technical',
  trade VARCHAR(60) DEFAULT '',
  other_skills VARCHAR(1000) DEFAULT '',
  experience_years INT DEFAULT 0,
  qualifications VARCHAR(1000) DEFAULT '',
  certifications VARCHAR(1000) DEFAULT '',
  previous_projects VARCHAR(3000) DEFAULT '',
  availability VARCHAR(60) DEFAULT '',
  expected_rate VARCHAR(60) DEFAULT '',
  rate_unit VARCHAR(20) DEFAULT 'per_day',
  has_tools TINYINT(1) NOT NULL DEFAULT 0,
  has_transport TINYINT(1) NOT NULL DEFAULT 0,
  cv VARCHAR(20) DEFAULT NULL,
  certificate_file VARCHAR(20) DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  score INT DEFAULT 0,
  review_notes VARCHAR(2000) DEFAULT '',
  reviewed_by VARCHAR(20) DEFAULT NULL,
  contractor VARCHAR(20) DEFAULT NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_applications_status (status),
  INDEX idx_applications_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS project_assignments (
  id VARCHAR(20) PRIMARY KEY,
  project VARCHAR(20) DEFAULT NULL,
  contractor VARCHAR(20) DEFAULT NULL,
  role_on_project VARCHAR(120) DEFAULT '',
  scope_of_work VARCHAR(3000) DEFAULT '',
  payment_basis VARCHAR(20) DEFAULT 'fixed',
  agreed_amount DECIMAL(14,2) DEFAULT 0,
  currency VARCHAR(10) DEFAULT 'RWF',
  start_date VARCHAR(20) DEFAULT '',
  end_date VARCHAR(20) DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'offered',
  contract_signed TINYINT(1) NOT NULL DEFAULT 0,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
  amount_paid DECIMAL(14,2) DEFAULT 0,
  performance_rating INT DEFAULT 0,
  notes VARCHAR(2000) DEFAULT '',
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_assign_project (project),
  INDEX idx_assign_contractor (contractor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
